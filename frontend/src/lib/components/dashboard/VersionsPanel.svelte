<script lang="ts">
	import { onMount } from 'svelte';
	import { read, formatDate } from '#lib/dashboard';
	import { newerVersion, buildState, buildReleaseUrl } from '#lib/versions';
	type Build = { version: string; revision: string | null };
	type Status = {
		backend: Build;
		latest_version: string | null;
		release_url: string | null;
		attempted_at: string | null;
		checked_at: string | null;
		error: string | null;
	};
	const frontend: Build = { version: __APP_VERSION__, revision: __APP_REVISION__ };
	let status = $state<Status | null>(null);
	let error = $state('');
	const updateAvailable = $derived(
		status?.latest_version &&
			[frontend.version, status.backend.version].some((installed) =>
				newerVersion(status!.latest_version!, installed)
			)
	);
	onMount(async () => {
		try {
			status = await read<Status>('versions');
		} catch (cause) {
			error = (cause as Error).message;
		}
	});
</script>

<!-- eslint-disable svelte/no-navigation-without-resolve -- External GitHub links are generated by the backend. -->
<section class="workspace-panel versions-card" aria-label="Versions de l’application">
	<p class="eyebrow">Maintenance</p>
	<h3 class="title is-6 mb-3">Versions de l’application</h3>
	{#if error}<p class="notification is-danger is-light" role="alert">{error}</p>
	{:else if !status}<p role="status">Chargement des versions…</p>
	{:else}
		<div class="table-container">
			<table class="table is-fullwidth">
				<caption class="is-sr-only"
					>Versions et révisions des composants en cours d’exécution</caption
				>
				<thead
					><tr
						><th scope="col">Composant</th><th scope="col">Version</th><th scope="col">Révision</th
						></tr
					></thead
				>
				<tbody
					>{#each [{ name: 'Frontend', ...frontend }, { name: 'Backend', ...status.backend }] as build (build.name)}
						{@const state = buildState(build.version, build.revision, status.latest_version)}
						{@const releaseUrl = buildReleaseUrl(
							build.version,
							status.latest_version,
							status.release_url
						)}
						<tr
							><th scope="row">{build.name}</th><td
								>{#if releaseUrl}<a href={releaseUrl} target="_blank" rel="noopener noreferrer"
										>{build.version}</a
									>{:else}{build.version}{/if}</td
							><td>
								<span
									class="tag"
									class:is-success={state === 'current'}
									class:is-danger={state === 'behind'}
									class:experimental={state === 'experimental'}
								>
									{#if releaseUrl}<a
											href={releaseUrl}
											target="_blank"
											rel="noopener noreferrer"
											title={build.revision ?? undefined}
											>{build.revision?.slice(0, 7) ?? 'Inconnue'}</a
										>{:else}<span title={build.revision ?? undefined}
											>{build.revision?.slice(0, 7) ?? 'Inconnue'}</span
										>{/if}
									{#if state === 'behind'}
										<span class="revision-label">— ⚠ À mettre à jour</span>
									{:else if state === 'experimental'}
										<span class="revision-label">(expérimental)</span>{/if}
								</span></td
							></tr
						>
					{/each}</tbody
				>
			</table>
		</div>
		{#if frontend.version !== status.backend.version || (frontend.revision && status.backend.revision && frontend.revision !== status.backend.revision)}
			<p class="notification is-warning is-light" role="status">
				Le frontend et le backend utilisent des versions ou des révisions différentes.
			</p>
		{/if}
		{#if status.error}<p class="notification is-warning is-light" role="status">
				{status.error} Le dernier résultat connu est conservé.
			</p>{/if}
		{#if updateAvailable && status.release_url}
			<p class="notification is-danger is-light" role="status">
				La version {status.latest_version} est disponible. Mettez l’application à jour. Préparez la migration
				après consultation des instructions et sauvegarde des données.
				<a href={status.release_url} target="_blank" rel="noopener noreferrer"
					>Consulter la nouvelle release</a
				>
			</p>
		{:else if status.latest_version && status.release_url}
			<p>
				Dernière version stable publiée : <a
					href={status.release_url}
					target="_blank"
					rel="noopener noreferrer">{status.latest_version}</a
				>.
			</p>
		{:else if status.checked_at}<p>Aucune release stable publiée.</p>{/if}
		{#if status.checked_at}<p class="help">
				Dernière vérification réussie : {formatDate(status.checked_at)}
			</p>{/if}
		{#if status.attempted_at}<p class="help">
				Dernière tentative : {formatDate(status.attempted_at)} · Vérification au plus une fois par 24
				heures à l’ouverture du dashboard.
			</p>{/if}
	{/if}
</section>

